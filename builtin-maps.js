// ---------- generated mazes (fixed seed, so they never change) ----------
function bigMaze() {
  const W = 31, H = 25, R = rng(20261109);
  const g = Array.from({ length: H }, () => Array(W).fill('#'));
  // recursive backtracker on odd cells
  const st = [[1, 3]]; g[3][1] = '.';
  while (st.length) {
    const [x, y] = st[st.length - 1];
    const nb = [[2, 0], [-2, 0], [0, 2], [0, -2]].map(([dx, dy]) => [x + dx, y + dy, dx, dy]).filter(([nx, ny]) => nx > 0 && ny > 2 && nx < W - 1 && ny < H - 1 && g[ny][nx] === '#');
    if (!nb.length) { st.pop(); continue; }
    const [nx, ny, dx, dy] = nb[Math.floor(R() * nb.length)];
    g[y + dy / 2][x + dx / 2] = '.'; g[ny][nx] = '.'; st.push([nx, ny]);
  }
  // braid: knock out some walls so there are loops and shortcuts
  for (let y = 3; y < H - 1; y++) for (let x = 1; x < W - 1; x++) {
    if (g[y][x] !== '#') continue;
    const h = g[y][x - 1] === '.' && g[y][x + 1] === '.', v = g[y - 1]?.[x] === '.' && g[y + 1]?.[x] === '.';
    if ((h || v) && R() < 0.12) g[y][x] = R() < 0.3 ? 'B' : '.';
  }
  // start strip on top, finish bottom-right, a few goodies
  for (let x = 1; x < W - 1; x++) { g[1][x] = '.'; g[2][x] = x % 2 ? '.' : '#'; }
  '12345678'.split('').forEach((c, i) => { g[1][1 + i * 2] = c; });
  g[H - 2][W - 2] = 'F'; g[H - 2][W - 3] = 'F'; g[H - 3][W - 2] = 'F';
  let placed = 0;
  while (placed < 10) {
    const x = 1 + Math.floor(R() * (W - 2)), y = 4 + Math.floor(R() * (H - 6));
    if (g[y][x] === '.') { g[y][x] = '?s>~f'[placed % 5]; placed++; }
  }
  return g.map(r => r.join(''));
}

function forest() {
  const W = 26, H = 20, R = rng(77);
  const g = Array.from({ length: H }, (_, y) => Array.from({ length: W }, (_, x) => (x === 0 || y === 0 || x === W - 1 || y === H - 1 ? '#' : '.')));
  for (let y = 4; y < H - 3; y++) for (let x = 1; x < W - 1; x++) {
    const r = R();
    if (r < 0.16) g[y][x] = '#';
    else if (r < 0.22) g[y][x] = '~';
    else if (r < 0.235) g[y][x] = 'B';
    else if (r < 0.245) g[y][x] = '?';
  }
  for (let x = 1; x < W - 1; x++) { g[1][x] = '.'; g[2][x] = '.'; g[3][x] = '.'; }
  '12345678'.split('').forEach((c, i) => { g[1][2 + i * 3] = c; });
  for (let x = 10; x < 16; x++) { g[H - 2][x] = 'F'; g[H - 3][x] = '.'; }
  return g.map(r => r.join(''));
}

function extraMazes(mazeFromArt) {
  const out = ART.map(([id, name, opts, art], i) => mazeFromArt(id, name, art, opts, 20 + i));
  out.push(mazeFromArt('maze-big', 'المتاهة الكبيرة', bigMaze(), { timeLimit: 240, speed: 2.4 }, 40));
  out.push(mazeFromArt('maze-forest', 'الغابة', forest(), { speed: 1.9, movement: 'auto' }, 41));
  return out;
}

// ---------- extra block-breaker maps ----------
function breakoutMap(id, name, cols, rows, palette, paint, extra = {}, updated = 0) {
  const cells = new Array(cols * rows).fill(0);
  for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) cells[r * cols + c] = paint(c, r) || 0;
  return {
    id, name, author: 'النظام', authorId: 'system', cols, rows, palette, cells,
    dropChance: 0.1, items: ['multi3', 'wide', 'fire', 'laser', 'shield', 'life', 'bomb', 'slow'],
    ballSpeed: 5, lives: 3, paddleWidth: 100, updated, ...extra,
  };
}

function extraBreakout() {
  const pyramid = breakoutMap('pyramid', 'الهرم', 40, 30, ['#e0b040', '#c9902c', '#a86d1f', '#5b8cff'], (c, r) => {
    if (r === 0 || c === 0 || c === 39) return 1;
    const half = Math.floor((r - 2) * 0.75);
    if (r >= 2 && r < 27 && Math.abs(c - 19.5) <= half) return (r % 6 === 5) ? 1 : 2 + (Math.floor(r / 3) % 3);
    if (r < 2) return 5;
    return 0;
  }, { dropChance: 0.08 }, 30);
  const heart = breakoutMap('heart', 'القلب', 40, 30, ['#ff4d6d', '#c9184a', '#ffb3c1'], (c, r) => {
    if (r === 0 || c === 0 || c === 39) return 1;
    const x = (c - 19.5) / 14, y = -(r - 14) / 12;
    const v = (x * x + y * y - 1) ** 3 - x * x * y * y * y;
    if (v <= 0) return (r + c) % 7 === 0 ? 4 : (r < 10 ? 2 : 3);
    return 0;
  }, { ballSpeed: 5.5 }, 31);
  return [pyramid, heart];
}

